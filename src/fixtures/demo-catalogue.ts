const sharedFixtureById = new Map<string, ShopMapSummary>(
  demoShops.map((shop) => [shop.id, shop]),
);

function toDetail(seed: DemoSeed): ShopDetail {
  const shared = sharedFixtureById.get(seed.id);
  const summary: ShopMapSummary = shared ?? {
    id: seed.id,
    slug: seed.slug,
    name: seed.name,
    ...(seed.localName === undefined ? {} : { localName: seed.localName }),
    countryCode: seed.countryCode,
    localityName: seed.localityName,
    position: { latitude: seed.latitude, longitude: seed.longitude },
    primaryType: seed.primaryType,
    specialtyLine: seed.specialties[0] ?? seed.services[0] ?? null,
    operationalStatus: seed.operationalStatus ?? "open",
    markerState: seed.markerState,
    sourceQuality: "demo",
    fixtureNotice: FIXTURE_NOTICE,
  };

  const shopTypes: readonly ShopType[] = [
    summary.primaryType,
    ...(seed.extraTypes ?? []).filter((type) => type !== summary.primaryType),
  ];

  return {
    ...summary,
    shortDescription: seed.shortDescription,
    addressLines: seed.addressLines,
    ...(seed.neighbourhood === undefined ? {} : { neighbourhood: seed.neighbourhood }),
    timezone: TIMEZONES[summary.countryCode],
    shopTypes,
    specialties: seed.specialties,
    services: seed.services,
    brands: seed.brands,
    appointmentRequired: seed.appointmentRequired ?? false,
    ...(seed.accessibilityNotes === undefined
      ? {}
      : { accessibilityNotes: seed.accessibilityNotes }),
    openingHours: HOURS[seed.hours],
    ...(seed.hoursNote === undefined ? {} : { openingHoursNote: seed.hoursNote }),
    links: [DEMO_LINK],
    provenance: {
      lastVerifiedAt: seed.lastVerifiedAt ?? null,
      summary: "Demo fixture record. No source has been verified for this listing.",
    },
    stamp: {
      id: `stamp-${seed.slug}`,
      motif: seed.motif,
      ink: seed.ink,
      localityLabel: seed.localityName,
      countryLabel: COUNTRY_LABELS[summary.countryCode],
      designVersion: 1,
    },
  };
}

export const demoShopDetails: readonly ShopDetail[] = seeds.map(toDetail);

